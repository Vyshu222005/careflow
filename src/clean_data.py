"""Clean and validate the Sepsis event log.

Steps:
    1. Drop rows missing case ID, activity or timestamp.
    2. Parse timestamps (UTC).
    3. Drop duplicate events (same case, activity and timestamp).
    4. Sort events by case and time (stable, so ties keep their file order).
    5. Fill case-level attributes (Age, flags, ...) across every event of the case.
    6. Remove cases with broken order: ER Registration is not the first event.

Usage:
    python src/clean_data.py

Outputs:
    data/processed/sepsis_clean.csv
    reports/data_quality_report.md
"""
from pathlib import Path

import pandas as pd

from load_data import ACTIVITY, CASE_ID, RESOURCE, TIMESTAMP, load_event_log

ROOT = Path(__file__).resolve().parents[1]
CLEAN_PATH = ROOT / "data" / "processed" / "sepsis_clean.csv"
REPORT_PATH = ROOT / "reports" / "data_quality_report.md"

LIFECYCLE = "lifecycle:transition"
START_ACTIVITY = "ER Registration"

# Measured values belong to one event, so a missing value is genuinely "not measured".
EVENT_COLUMNS = [CASE_ID, ACTIVITY, TIMESTAMP, RESOURCE, LIFECYCLE, "CRP", "LacticAcid", "Leucocytes"]
# Everything else describes the patient/case and is constant within a case.
UNKNOWN_DIAGNOSIS = "Unknown"


def _snapshot(step: str, df: pd.DataFrame) -> dict:
    return {"step": step, "events": len(df), "cases": df[CASE_ID].nunique()}


def _missing_percent(df: pd.DataFrame) -> pd.Series:
    return df.isna().mean().mul(100).round(1)


def case_attribute_columns(df: pd.DataFrame) -> list:
    return [c for c in df.columns if c not in EVENT_COLUMNS]


def fill_case_attributes(df: pd.DataFrame) -> pd.DataFrame:
    """Copy each case attribute to all events of the case, and fix dtypes."""
    df = df.copy()
    for col in case_attribute_columns(df):
        df[col] = df.groupby(CASE_ID)[col].transform("first")
        if df[col].dtype == object:
            df[col] = df[col].astype("boolean")
    df["Diagnose"] = df["Diagnose"].fillna(UNKNOWN_DIAGNOSIS)
    return df


def broken_order_cases(df: pd.DataFrame) -> pd.Index:
    """Cases (df must be sorted) whose first event is not the ER Registration."""
    first = df.groupby(CASE_ID, sort=False)[ACTIVITY].first()
    return first[first != START_ACTIVITY].index


def clean_event_log(raw: pd.DataFrame):
    """Return (clean log, report dict)."""
    steps = [_snapshot("Raw log", raw)]
    df = raw.copy()

    core = [CASE_ID, ACTIVITY, TIMESTAMP]
    df = df.dropna(subset=core)
    steps.append(_snapshot("Drop rows missing case/activity/timestamp", df))

    df[TIMESTAMP] = pd.to_datetime(df[TIMESTAMP], utc=True)
    df[CASE_ID] = df[CASE_ID].astype(str)

    df = df.drop_duplicates(subset=core, keep="first")
    steps.append(_snapshot("Drop duplicate events", df))

    df = df.sort_values([CASE_ID, TIMESTAMP], kind="stable").reset_index(drop=True)
    df = fill_case_attributes(df)

    bad_cases = broken_order_cases(df)
    df = df[~df[CASE_ID].isin(bad_cases)].reset_index(drop=True)
    steps.append(_snapshot("Remove cases not starting with ER Registration", df))

    # Warning only: events after discharge, other than a legitimate return to the ER.
    released = df[ACTIVITY].str.startswith("Release")
    after_release = df.groupby(CASE_ID)[ACTIVITY].transform(lambda s: s.str.startswith("Release").cummax())
    late = df[after_release & ~released & (df[ACTIVITY] != "Return ER")]

    report = {
        "steps": steps,
        "removed_cases": sorted(bad_cases),
        "missing_before": _missing_percent(raw),
        "missing_after": _missing_percent(df),
        "late_events": len(late),
        "late_cases": late[CASE_ID].nunique(),
        "duplicates_removed": steps[1]["events"] - steps[2]["events"],
        "start": df[TIMESTAMP].min(),
        "end": df[TIMESTAMP].max(),
    }
    return df, report


def write_report(report: dict, path: Path = REPORT_PATH) -> None:
    steps = report["steps"]
    raw, final = steps[0], steps[-1]
    lines = [
        "# Data Quality Report",
        "",
        "Generated by `src/clean_data.py` from `data/raw/sepsis.xes`.",
        "",
        "## Before vs after",
        "",
        "| | Before | After | Removed |",
        "|---|---|---|---|",
        f"| Cases | {raw['cases']:,} | {final['cases']:,} | {raw['cases'] - final['cases']:,} |",
        f"| Events | {raw['events']:,} | {final['events']:,} | {raw['events'] - final['events']:,} |",
        "",
        "## Cleaning steps",
        "",
        "| Step | Events | Cases |",
        "|---|---|---|",
    ]
    lines += [f"| {s['step']} | {s['events']:,} | {s['cases']:,} |" for s in steps]

    lines += [
        "",
        "## Issues found",
        "",
        f"- **Duplicate events:** {report['duplicates_removed']} rows repeated the same case, activity and timestamp "
        "(repeated lab results). The first was kept.",
        f"- **Broken order:** {len(report['removed_cases'])} cases do not start with `ER Registration`; "
        "other events are timestamped before the patient was registered, so the pathway cannot be trusted. "
        "These cases were removed.",
        f"- **Events after discharge:** {report['late_events']} events in {report['late_cases']} cases "
        "(late lab results or admissions after a `Release`). Kept and flagged. A `Return ER` after discharge is "
        "valid and was not counted.",
        "- **Timestamps:** parsed as UTC. No missing or unparsable timestamps were found.",
        "- **Sort order:** events are sorted by case and time. Events with identical timestamps keep their original order.",
        "- **Case attributes:** Age, diagnostic flags and SIRS criteria were recorded on one event only. "
        "They are now copied to every event of the case. Cases with no `Diagnose` are labelled `Unknown`.",
        "- **Measurements:** `CRP`, `LacticAcid` and `Leucocytes` stay empty when not measured on that event.",
        "",
        "## Missing values (% of events)",
        "",
        "| Column | Before | After |",
        "|---|---|---|",
    ]
    before, after = report["missing_before"], report["missing_after"]
    for col in before.index:
        if before[col] or after[col]:
            lines.append(f"| {col} | {before[col]} | {after[col]} |")

    lines += [
        "",
        "## Removed cases",
        "",
        ", ".join(f"`{c}`" for c in report["removed_cases"]),
        "",
    ]
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text("\n".join(lines), encoding="utf-8")


def load_clean_log(path: Path = CLEAN_PATH) -> pd.DataFrame:
    """Read the cleaned CSV back.

    One case is literally named "NA", which pandas would read as missing by default,
    so only empty cells are treated as missing here.
    """
    return pd.read_csv(path, keep_default_na=False, na_values=[""], parse_dates=[TIMESTAMP])


def main() -> pd.DataFrame:
    clean, report = clean_event_log(load_event_log())
    CLEAN_PATH.parent.mkdir(parents=True, exist_ok=True)
    clean.to_csv(CLEAN_PATH, index=False)
    write_report(report)

    raw, final = report["steps"][0], report["steps"][-1]
    print(f"Cases : {raw['cases']:,} -> {final['cases']:,}")
    print(f"Events: {raw['events']:,} -> {final['events']:,}")
    print(f"Saved : {CLEAN_PATH}")
    print(f"Report: {REPORT_PATH}")
    return clean


if __name__ == "__main__":
    main()
